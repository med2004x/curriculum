#!/usr/bin/env python3
"""Regenerate the lesson and LIG code inventory."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
lessons = sorted((ROOT / "lessons").glob("[0-9][0-9][0-9]-*"))
lesson_files = [p for d in lessons for p in (d / "code").rglob("*") if p.is_file()]
challenges = [p for d in lessons for p in (d / "code").glob("challenge.*") if p.is_file()]
go_tests = [p for d in lessons for p in (d / "code").rglob("*_test.go")]
lig_code = [p for p in (ROOT / "LIG").rglob("*") if p.is_file() and p.suffix in {".py", ".sql"}]
lig_tests = [p for p in (ROOT / "LIG").rglob("test_*.py")]

lines = [
    "# Code artifact inventory", "",
    "Generated by `python tools/generate_code_inventory.py`.", "",
    f"- Engineering lessons: {len(lessons)}",
    f"- Files under `lessons/*/code/`: {len(lesson_files)}",
    f"- Distinct `challenge.*` source files: {len(challenges)}",
    f"- Go test files in engineering lessons: {len(go_tests)}",
    f"- Skipped Go tests: {sum('t.Skip' in p.read_text(errors='ignore') for p in go_tests)}",
    f"- LIG S1/S2 Python and SQL files (including tests): {len(lig_code)}",
    f"- LIG Python test files: {len(lig_tests)}", "",
    "## Engineering lesson workspaces", "",
    "| Lesson | Files | Representative source files |", "|---:|---:|---|",
]
for lesson in lessons:
    files = sorted(p for p in (lesson / "code").rglob("*") if p.is_file())
    sources = [p.name for p in files if p.suffix.lower() in {".c", ".go", ".rs", ".sql"}]
    lines.append(f"| {lesson.name[:3]} | {len(files)} | {', '.join(sources[:6]) or 'see code README'} |")

lines += ["", "## LIG semester practice workspaces", "", "| Semester | Subject packs | Practice code | Python tests |", "|---|---:|---:|---:|"]
for semester in ("S1", "S2"):
    folder = ROOT / "LIG" / semester
    packs = [p for p in folder.glob("*.md") if p.name != "README.md"]
    code = [p for p in (folder / "code").iterdir() if p.is_file() and not p.name.startswith("test_")]
    tests = list((folder / "code").glob("test_*.py"))
    lines.append(f"| {semester} | {len(packs)} | {len(code)} | {len(tests)} |")

(ROOT / "CODE-INVENTORY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote inventory: {len(lesson_files)} engineering files, {len(lig_code)} LIG source files")
