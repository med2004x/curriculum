# S1 COURSE EXERCISE - DIGITAL-SKILLS
# Study the prompts below, then complete the exercises in this file.

# # FSEGS LIG — Compétences numériques
#
# **Semester:** S1
# **Attached engineering lesson:** 003 — Types, Number Systems, and Git
#
# ## Scope
#
# File and directory management; naming conventions; operating-system basics; office productivity; document formatting; spreadsheet fundamentals; formulas and references; tables/charts; presentation design; web research; source evaluation; digital security; backups; password hygiene; collaboration/versioning; data privacy; reproducible student work.
#
# ## Required workflow
#
# Organise every course artifact predictably. Use meaningful filenames, version changes through Git where appropriate, and keep evidence with the work that generated it.
#
# For spreadsheets, understand cells, relative/absolute references, ranges, arithmetic, conditional logic, sorting/filtering, and basic charts. You should be able to reproduce a simple financial/statistical table without relying on a memorised click sequence.
#
# For documents and presentations, hierarchy, readability, source attribution, tables, figures, and concise structure matter more than decorative effects.
#
# ## Exercises
#
# 1. Create a clean semester folder structure without mixing drafts and final artifacts.
# 2. Rename a deliberately chaotic set of files using a consistent convention.
# 3. Build a spreadsheet that computes totals, averages, minimums, and percentages.
# 4. Demonstrate relative versus absolute cell references with a small table.
# 5. Turn a raw table into a correctly labelled chart and explain why the chosen chart fits.
# 6. Create a one-page technical report with title, objective, method, result, and source list.
# 7. Create a five-slide presentation from a short case without filling slides with paragraphs.
# 8. Compare three web sources and document author, date, evidence, and relevance.
# 9. Build a backup plan using two independent copies and a restore test.
# 10. Identify phishing, insecure sharing, weak passwords, and excessive permissions in a mini-case.
#
# ## Exam patterns
#
# Short command/operation questions; identify correct spreadsheet formulas; fix a broken table; choose an appropriate visualisation; evaluate a source; explain backup/security practices.
#
# ## Mastery gate
#
# Produce one spreadsheet, one structured document, one five-slide presentation, and one source-evaluation table from raw material without hand-holding. Everything must be named and organised so another student can open it and understand it.
