# S1 COURSE EXERCISE - BUSINESS-COMMUNICATION
# Study the prompts below, then complete the exercises in this file.

# # FSEGS LIG — Business Communication 1 (English)
#
# **Semester:** S1  
# **Attached engineering lesson:** 011 — Testing, Verification, and Reading Code
#
# ## Scope
#
# Professional vocabulary; sentence structure; clarity and concision; formal email; requests and responses; describing procedures; reporting results; summarising information; basic meeting language; technical explanation for a non-specialist; presentation structure.
#
# ## Language targets
#
# Use precise subjects and verbs. Prefer direct sentences over vague formulations. Distinguish fact, interpretation, recommendation, and uncertainty. Use headings, bullets, tables, and short paragraphs when they improve retrieval.
#
# Typical technical verbs: define, identify, compare, compute, verify, reproduce, diagnose, implement, evaluate, recommend, document.
#
# ## Worked tasks
#
# 1. Rewrite a vague bug report into a reproducible report containing environment, steps, expected result, actual result, and evidence.
# 2. Turn a technical paragraph into a 120-word executive summary.
# 3. Write a polite professional email requesting missing information and specifying a deadline.
#
# ## Exercises
#
# 1. Define ten IT terms in one sentence each.
# 2. Compare two technologies using a structured table.
# 3. Write a 150-word explanation of a loop or data structure for a business audience.
# 4. Convert informal chat text into a professional email.
# 5. Write a meeting agenda and a five-line meeting summary.
# 6. Summarise a technical article while preserving its main claim and evidence.
# 7. Write a short incident report with a timeline.
# 8. Present a recommendation using problem → evidence → options → decision.
# 9. Edit a paragraph for grammar, ambiguity, repetition, and unsupported claims.
# 10. Deliver a two-minute spoken explanation and then compress it to 120 written words.
#
# ## Exam patterns
#
# Vocabulary matching; correction; short professional writing; summary; email; structured response to a scenario; short presentation outline.
#
# ## Mastery gate
#
# Write a professional email, a concise technical explanation, and a one-page incident summary from unseen prompts with no grammar checker doing the thinking for you.
