# ## Teaching notes
#
# `P → Q` is false only when `P` is true and `Q` is false. Its contrapositive is `¬Q → ¬P`; its converse is `Q → P`, which is not generally equivalent.
#
# Negating `∀x P(x)` produces `∃x ¬P(x)`. Negating `∃x P(x)` produces `∀x ¬P(x)`.
#
# A proof should state assumptions, transformations, and conclusion. A counterexample is enough to refute a universal claim; one example is never enough to prove one.
